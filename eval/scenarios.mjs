// The simulated caller's instructions for its own Voice Agent session.
export function callerPrompt(scenario) {
  const c = scenario.caller
  const lines = [
    'You are a caller on a real phone call to the phone agent of a job candidate named Maya Chen. Speak like a person on the phone: short, natural sentences, one or two per turn. Never say you are an AI, and never mention a test or a role-play.',
    '',
    `Who you are: ${c.persona}`,
    'What you know. Share each fact when you are asked about it, unless your behavior says otherwise:',
    ...c.facts.map((f) => `- ${f}`),
    c.email ? `- Your email address is ${c.email}.` : null,
    `How you behave: ${c.behavior}`,
    '',
    'On the call:',
    '- The agent speaks first. Then say who you are and why you are calling.',
    '- Answer what you are asked. If the agent reads details back, say yes if they are right, or correct them.',
    c.email ? `- If asked for your email, spell it slowly, the way people do on the phone: "${c.emailSpoken}".` : '- If asked for an email address, say you would rather not give one.',
    '- If the agent offers times for a call, choose the first time offered.',
    '- When the agent says goodbye, say a short goodbye, then call the hang_up tool.',
    '- If the agent says it will end the call, say goodbye and call the hang_up tool.',
  ]
  return lines.filter((l) => l !== null).join('\n')
}

